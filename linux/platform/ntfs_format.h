#pragma once
#include "format_command.h"
#include <QString>

namespace rufus
{
constexpr quint32 NtfsCompressionClusterBytes = 4096;
// Prewrite capability check: provider defaults differ between ntfsprogs-plus
// and NTFS-3G. Unsupported quick-only providers must fail before partitioning.
int CheckNtfsFullFormatTools(const QString& mkfs);
struct NtfsFormatOptions
{
    quint64 size = 0;
    quint64 partitionOffset = 0; // Disk offset recorded in the BPB, not an I/O offset.
    quint32 clusterSize = 0;
    QString label; // At most 32 UTF-16 units. Callers apply Rufus label normalization.
    bool quickFormat = true;
    bool compression = false;
    bool indexing = false;
    quint32 sectorSize = 512;
    quint32 physicalSectorSize = 512;
};

struct NtfsFormatResult
{
    FORMAT_RESULT format = {};
    quint64 volumeId = 0; // Generated by mkntfs and read from the formatted volume.
};

// Quick-format an existing, exclusively borrowed, partition-sized regular file.
// The caller retains its O_RDWR descriptor, flags and seek position. Require
// exact capacity, requested 512/1024/2048/4096-byte logical/physical geometry and an explicit Rufus NTFS cluster
// size. mkntfs must be a trusted absolute path. No shell or authorization.
// Unlike mkfs.fat, mkntfs cannot offset writes inside a whole-disk file: I/O
// starts at byte zero; partitionOffset supplies --partition-start metadata only.
// Shared child supervision handles cancellation, timeout, reaping and flush.
// Verify geometry, complete primary/backup logical boot sectors and MFT/MFTMirr headers afterward.
// This is not a full filesystem check; tests inspect labels and NTFS metadata
// with native tools. Failure after started=true can leave an incomplete volume.
// No mounting, boot-payload writing or GUI integration here.
int CheckNtfsFormatOptions(const NtfsFormatOptions& options);
int CheckNtfsImageRequest(int fd, const QString& mkfs, const NtfsFormatOptions& options);
int FormatNtfsImage(int fd, const QString& mkfs, const NtfsFormatOptions& options, NtfsFormatResult& result);

// Verify an already-formatted native NTFS partition before replacing its
// primary boot code. The formatter's primary/backup sectors must still match.
// Does not write, open another descriptor or infer a host filesystem setting.
int CheckNtfsFormattedVolume(int fd, quint64 device, const NtfsFormatOptions& options);

// Already authorized, retained block-device descriptor. Recheck expected dev_t,
// capacity, sector size and read-only state before/after formatting. The caller
// must retain a whole-disk claim throughout, and check mount/use and disk identity.
// Partition formatting uses no force option. Whole-device SFD requires it; the
// caller must first clear the table and verify no kernel partitions remain.
// Whole-device requests require partitionOffset == 0.
int FormatNtfsDevice(int fd, quint64 device, const QString& mkfs,
    const NtfsFormatOptions& options, NtfsFormatResult& result, bool wholeDevice = false);
}
